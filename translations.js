// Language switching function
let currentLang = 'en';

function getI18nValue(lang, key) {
  const [section, subkey] = key.split('.');
  if (translations[section] && translations[section][lang] && translations[section][lang][subkey]) {
    return translations[section][lang][subkey];
  }
  return null;
}

function switchLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;

  // Save language preference to localStorage
  localStorage.setItem('preferredLanguage', lang);

  // Update active state on language buttons
  document.querySelectorAll('.lang-toggle button').forEach(btn => {
    btn.classList.remove('active');
    btn.setAttribute('aria-pressed', 'false');
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
      btn.setAttribute('aria-pressed', 'true');
    }
  });

  // Translate all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const value = getI18nValue(lang, key);
    if (value) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = value;
      } else {
        el.innerHTML = value;
      }
    }
  });

  document.querySelectorAll('[data-i18n-text]').forEach((el) => {
    const key = el.getAttribute('data-i18n-text');
    const value = getI18nValue(lang, key);
    if (value) {
      el.textContent = value;
    }
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    const key = el.getAttribute('data-i18n-aria-label');
    const value = getI18nValue(lang, key);
    if (value) {
      el.setAttribute('aria-label', value);
    }
  });

  document.querySelectorAll('[data-i18n-content]').forEach((el) => {
    const key = el.getAttribute('data-i18n-content');
    const value = getI18nValue(lang, key);
    if (value) {
      el.setAttribute('content', value);
    }
  });
}

// Initialize language on page load
document.addEventListener('DOMContentLoaded', () => {
  // Check for saved language preference, default to 'en' if none found
  const savedLang = localStorage.getItem('preferredLanguage') || 'en';
  switchLanguage(savedLang);
});
